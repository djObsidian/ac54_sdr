"""Extract RTL8822B init tables from rtw88 sources into a standalone C header."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = root / "ref" / "rtw88"
tbl = (src / "rtw8822b_table.c").read_text()
chip = (src / "rtw8822b.c").read_text()
out = ["/* AUTO-GENERATED by tools/gen_tables.py from rtw88 (GPL-2.0 OR BSD-3-Clause, Realtek) */",
       "#pragma once", "#include <stdint.h>", ""]

for name in ["mac", "agc", "bb", "rf_a", "rf_b"]:
    m = re.search(r"static const u32 rtw8822b_%s\[\] = \{(.*?)\n\};" % name, tbl, re.S)
    body = m.group(1)
    out.append("static const uint32_t t8822b_%s[] = {%s\n};" % (name, body))
    out.append("#define T8822B_%s_N (sizeof(t8822b_%s)/sizeof(uint32_t))" % (name.upper(), name))
    out.append("")

out += ["struct pwr_cmd { uint16_t offset; uint8_t cut_mask, intf_mask, base, cmd, mask, value; };",
        "#define BIT(n) (1u << (n))"]
for k, v in [("RTW_PWR_CMD_READ", 0), ("RTW_PWR_CMD_WRITE", 1), ("RTW_PWR_CMD_POLLING", 2),
             ("RTW_PWR_CMD_DELAY", 3), ("RTW_PWR_CMD_END", 4), ("RTW_PWR_ADDR_MAC", 0),
             ("RTW_PWR_ADDR_USB", 1), ("RTW_PWR_ADDR_PCIE", 2), ("RTW_PWR_ADDR_SDIO", 3),
             ("RTW_PWR_INTF_SDIO_MSK", "BIT(0)"), ("RTW_PWR_INTF_USB_MSK", "BIT(1)"),
             ("RTW_PWR_INTF_PCI_MSK", "BIT(2)"), ("RTW_PWR_INTF_ALL_MSK", "0x0F"),
             ("RTW_PWR_CUT_TEST_MSK", "BIT(0)"), ("RTW_PWR_CUT_A_MSK", "BIT(1)"),
             ("RTW_PWR_CUT_B_MSK", "BIT(2)"), ("RTW_PWR_CUT_C_MSK", "BIT(3)"),
             ("RTW_PWR_CUT_D_MSK", "BIT(4)"), ("RTW_PWR_CUT_E_MSK", "BIT(5)"),
             ("RTW_PWR_CUT_F_MSK", "BIT(6)"), ("RTW_PWR_CUT_G_MSK", "BIT(7)"),
             ("RTW_PWR_CUT_ALL_MSK", "0xFF"), ("RTW_PWR_DELAY_US", 0), ("RTW_PWR_DELAY_MS", 1)]:
    out.append("#define %s %s" % (k, v))

for name in ["trans_carddis_to_cardemu_8822b", "trans_cardemu_to_act_8822b",
             "trans_act_to_cardemu_8822b", "trans_cardemu_to_carddis_8822b"]:
    m = re.search(r"static const struct rtw_pwr_seq_cmd %s\[\] = \{(.*?)\n\};" % name, chip, re.S)
    # {offset, cut, intf, base, cmd, mask, value}  (struct order in rtw88 is offset,cut,intf,base:4,cmd:4,mask,value)
    out.append("static const struct pwr_cmd %s[] = {%s\n};" % (name, m.group(1)))
out.append("")
(root / "tools" / "t8822b.h").write_text("\n".join(out))
print("ok")
